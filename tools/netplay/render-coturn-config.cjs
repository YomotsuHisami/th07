const { chmodSync, mkdirSync, writeFileSync } = require('node:fs');
const { dirname, resolve } = require('node:path');

function fail(message) {
  throw new Error(message);
}

function envText(name, { required = false } = {}) {
  const value = String(process.env[name] || '').trim();
  if (required && !value) fail(`${name} is required`);
  if (/\r|\n/.test(value)) fail(`${name} must not contain newlines`);
  return value;
}

function envInt(name, fallback, min, max) {
  const raw = String(process.env[name] || '').trim();
  const value = raw ? Number.parseInt(raw, 10) : fallback;
  if (!Number.isInteger(value) || value < min || value > max)
    fail(`${name} must be an integer in ${min}..${max}`);
  return value;
}

function outputPath() {
  const index = process.argv.indexOf('--output');
  if (index < 0 || !process.argv[index + 1])
    fail('usage: node render-coturn-config.cjs --output PATH');
  return resolve(process.argv[index + 1]);
}

const realm = envText('TH07_TURN_REALM', { required: true });
const secret = envText('TH07_TURN_SHARED_SECRET', { required: true });
if (Buffer.byteLength(secret, 'utf8') < 24)
  fail('TH07_TURN_SHARED_SECRET must be at least 24 bytes');

const listeningPort = envInt('TH07_TURN_LISTENING_PORT', 3478, 1, 65535);
const tlsListeningPort = envInt('TH07_TURN_TLS_LISTENING_PORT', 5349, 1, 65535);
const minPort = envInt('TH07_TURN_MIN_PORT', 49152, 1024, 65535);
const maxPort = envInt('TH07_TURN_MAX_PORT', 65535, 1024, 65535);
if (minPort > maxPort) fail('TH07_TURN_MIN_PORT must not exceed TH07_TURN_MAX_PORT');

// Intentionally conservative defaults for the current ~10 Mbps VPS. TH07
// gameplay is far below these limits; they mainly bound accidental/hostile use.
const userQuota = envInt('TH07_TURN_USER_QUOTA', 12, 1, 10000);
const totalQuota = envInt('TH07_TURN_TOTAL_QUOTA', 256, 1, 1000000);
const maxBps = envInt('TH07_TURN_MAX_BPS', 131072, 1024, 1000000000);
const bpsCapacity = envInt('TH07_TURN_BPS_CAPACITY', 786432, 1024, 1000000000);

const listeningIp = envText('TH07_TURN_LISTENING_IP');
const relayIp = envText('TH07_TURN_RELAY_IP');
const externalIp = envText('TH07_TURN_EXTERNAL_IP');
const cert = envText('TH07_TURN_CERT');
const pkey = envText('TH07_TURN_PKEY');
if (!!cert !== !!pkey) fail('TH07_TURN_CERT and TH07_TURN_PKEY must be configured together');

const lines = [
  '# Generated by tools/netplay/render-coturn-config.cjs',
  '# Do not commit the rendered file: it contains TH07_TURN_SHARED_SECRET.',
  `listening-port=${listeningPort}`,
  `min-port=${minPort}`,
  `max-port=${maxPort}`,
  'fingerprint',
  'use-auth-secret',
  `static-auth-secret=${secret}`,
  `realm=${realm}`,
  'no-cli',
  'no-multicast-peers',
  'no-dtls',
  `user-quota=${userQuota}`,
  `total-quota=${totalQuota}`,
  `max-bps=${maxBps}`,
  `bps-capacity=${bpsCapacity}`,
  '',
  '# Do not let TURN clients use this VPS as a path into private/reserved IPv4 networks.',
  'denied-peer-ip=0.0.0.0-0.255.255.255',
  'denied-peer-ip=10.0.0.0-10.255.255.255',
  'denied-peer-ip=100.64.0.0-100.127.255.255',
  'denied-peer-ip=127.0.0.0-127.255.255.255',
  'denied-peer-ip=169.254.0.0-169.254.255.255',
  'denied-peer-ip=172.16.0.0-172.31.255.255',
  'denied-peer-ip=192.0.0.0-192.0.0.255',
  'denied-peer-ip=192.0.2.0-192.0.2.255',
  'denied-peer-ip=192.88.99.0-192.88.99.255',
  'denied-peer-ip=192.168.0.0-192.168.255.255',
  'denied-peer-ip=198.18.0.0-198.19.255.255',
  'denied-peer-ip=198.51.100.0-198.51.100.255',
  'denied-peer-ip=203.0.113.0-203.0.113.255',
  'denied-peer-ip=240.0.0.0-255.255.255.255',
];

if (listeningIp) lines.push(`listening-ip=${listeningIp}`);
if (relayIp) lines.push(`relay-ip=${relayIp}`);
if (externalIp) lines.push(`external-ip=${externalIp}`);

if (cert) {
  lines.push(
    `tls-listening-port=${tlsListeningPort}`,
    `cert=${cert}`,
    `pkey=${pkey}`,
    'no-tlsv1',
    'no-tlsv1_1',
  );
} else {
  // TURN/UDP and TURN/TCP remain available on listening-port. TURN/TLS is
  // enabled only when a real certificate/private-key pair is supplied.
  lines.push('no-tls');
}

const output = outputPath();
mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, `${lines.join('\n')}\n`, { mode: 0o600 });
try { chmodSync(output, 0o600); } catch {}
console.log(`coturn config written: ${output}`);
